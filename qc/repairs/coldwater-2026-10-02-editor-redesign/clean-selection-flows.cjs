const assert = require('node:assert/strict');
const { chromium } = require('/usr/local/lib/node_modules/@playwright/mcp/node_modules/playwright');
(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/local/bin/chromium', args: ['--no-sandbox', '--unsafely-treat-insecure-origin-as-secure=http://172.17.0.10:3000'] });
  const context = await browser.newContext({ permissions: ['clipboard-read', 'clipboard-write'] });
  const page = await context.newPage();
  await page.goto('http://172.17.0.10:3000/', { waitUntil: 'networkidle' });
  const editor = page.getByRole('textbox', { name: 'Code editor' });
  await editor.click(); await page.keyboard.press('ControlOrMeta+A');
  await page.evaluate(() => navigator.clipboard.writeText('alpha bravo charlie\nsecond line'));
  await page.keyboard.press('ControlOrMeta+V');
  await page.waitForFunction(() => document.querySelectorAll('#editor .line').length === 2);
  const first = await editor.locator('.line .text').first().boundingBox();
  const second = await editor.locator('.line .text').nth(1).boundingBox();
  const copy = async () => { await page.keyboard.press('ControlOrMeta+C'); return page.evaluate(() => navigator.clipboard.readText()); };
  await page.mouse.dblclick(first.x + 17, first.y + first.height / 2);
  const word = await copy();
  assert.equal(word, 'alpha');
  await page.mouse.click(first.x + 17, first.y + first.height / 2, { clickCount: 3 });
  const line = await copy();
  assert.equal(line, 'alpha bravo charlie\n');
  await page.mouse.move(first.x + 25, first.y + first.height / 2);
  await page.mouse.down();
  await page.mouse.move(second.x + 35, second.y + second.height / 2, { steps: 8 });
  await page.mouse.up();
  const dragged = await copy();
  assert.equal(dragged.includes('\n'), true);
  console.log(JSON.stringify({ word, line, dragged }));
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
